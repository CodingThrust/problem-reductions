import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

const root = new URL('../docs/website/', import.meta.url);
const output = new URL('src/generated/', root);
let input = '';
process.stdin.setEncoding('utf8');
for await (const chunk of process.stdin) input += chunk;
const wasmSchemas = JSON.parse(input);
await mkdir(output, { recursive: true });
await writeFile(new URL('wasm-schemas.json', output), JSON.stringify(wasmSchemas));
const schemas = { ...wasmSchemas };
for (const name of ['atlas-data', 'graph-details', 'graph-scene', 'native-exports', 'path-graph']) {
  schemas[name] = JSON.parse(await readFile(new URL(name + '.schema.json', root), 'utf8'));
}
for (const [name, schema] of Object.entries(schemas)) {
  const types = await compile(schema, schema.title, {
    bannerComment: '/* Generated by scripts/generate_website_contracts.mjs; do not edit. */',
    unknownAny: true,
    additionalProperties: false,
  });
  await writeFile(new URL(name + '.d.mts', output), types);
}
