import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';
import { build } from 'vite';

const root = new URL('../', import.meta.url);
const outputs = {};
for (const [name, exportName] of [['graph-scene', 'validateGraphScene'], ['graph-details', 'validateGraphDetails'],
  ['wasm-paths', 'validateWasmPaths']]) {
  const schema = JSON.parse(await readFile(new URL(`docs/website/${name}.schema.json`, root), 'utf8'));
  const ajv = new Ajv2020({ strict: true, code: { source: true } });
  ajv.addSchema(schema);
  const types = await compile(schema, schema.title, {
    bannerComment: '/* Generated by scripts/generate_website_contracts.mjs; do not edit. */',
    unknownAny: true,
  });
  // Bundle standalone validators and their static helpers; the browser never compiles schemas.
  const cache = new URL('node_modules/.cache/', root);
  await mkdir(cache, { recursive: true });
  const temporary = await mkdtemp(fileURLToPath(new URL('website-contract-', cache)));
  let validator;
  try {
    await writeFile(resolve(temporary, 'validator.cjs'), standaloneCode(ajv, { [exportName]: schema.$id }));
    await writeFile(resolve(temporary, 'entry.mjs'), `export {${exportName}} from "./validator.cjs";\n`);
    const result = await build({
      configFile: false, root: fileURLToPath(root), publicDir: false, logLevel: 'error',
      build: { write: false, minify: true, lib: { entry: resolve(temporary, 'entry.mjs'), formats: ['es'] } },
    });
    const chunk = (Array.isArray(result) ? result : [result]).flatMap(result => result.output)
      .find(item => item.type === 'chunk');
    if (!chunk?.exports.includes(exportName)) throw new Error(`The compiled ${name} validator is missing`);
    validator = chunk.code;
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
  outputs[`docs/website/assets/${name}.validator.mjs`] = validator;
  outputs[`docs/website/assets/${name}.validator.d.mts`] = types +
    `\nexport declare function ${exportName}(value: unknown): value is ${schema.title};\n`;
}
for (const [name, content] of Object.entries(outputs)) {
  const path = new URL(name, root);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Contract drift: ${fileURLToPath(path)}`);
  } else {
    await writeFile(path, content);
  }
}
