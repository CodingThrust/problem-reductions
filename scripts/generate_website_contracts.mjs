import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';
import { build } from 'vite';

const root = new URL('../', import.meta.url);
const outputs = {};
// One build lets all standalone entries share Ajv's static runtime helpers.
const cache = new URL('node_modules/.cache/', root);
await mkdir(cache, { recursive: true });
const temporary = await mkdtemp(fileURLToPath(new URL('website-contract-', cache)));
const entries = {};
try {
  for (const [name, exportName] of [['graph-scene', 'validateGraphScene'], ['graph-details', 'validateGraphDetails'],
    ['wasm-paths', 'validateWasmPaths'], ['wasm-comparison', 'validateWasmComparison'], ['path-graph', 'validatePathGraph'],
    ['path-worker-request', 'validatePathRequestEnvelope'], ['path-worker-reply', 'validatePathReplyEnvelope'], ['atlas-data', 'validateAtlas'], ['wasm-path-request', 'validateWasmPathRequest'],
    ['wasm-comparison-request', 'validateWasmComparisonRequest'], ['native-exports', 'validateNativeExports']]) {
    const schema = JSON.parse(await readFile(new URL(`docs/website/${name}.schema.json`, root), 'utf8'));
    const ajv = new Ajv2020({ strict: true, code: { source: true } });
    ajv.addSchema(schema);
    const types = await compile(schema, schema.title, {
      bannerComment: '/* Generated by scripts/generate_website_contracts.mjs; do not edit. */',
      unknownAny: true,
      additionalProperties: false,
    });
    await writeFile(resolve(temporary, `${name}.cjs`), standaloneCode(ajv, { [exportName]: schema.$id }));
    const entry = resolve(temporary, `${name}.mjs`);
    await writeFile(entry, `export {${exportName}} from "./${name}.cjs";\n`);
    entries[`${name}.validator`] = entry;
    outputs[`docs/website/src/generated/${name}.validator.d.mts`] = types +
      `\nexport declare function ${exportName}(value: unknown): value is ${schema.title};\n`;
  }
  const result = await build({
    configFile: false, root: fileURLToPath(root), publicDir: false, logLevel: 'error',
    build: { write: false, minify: true,
      rolldownOptions: { input: entries, preserveEntrySignatures: 'strict', output: {
        entryFileNames: '[name].mjs', chunkFileNames: 'validator-runtime.mjs',
      } },
    },
  });
  for (const item of (Array.isArray(result) ? result : [result]).flatMap(result => result.output)) {
    if (item.type === 'chunk') outputs[`docs/website/src/generated/${item.fileName}`] = item.code;
  }
} finally {
  await rm(temporary, { recursive: true, force: true });
}
for (const [name, content] of Object.entries(outputs)) {
  const path = new URL(name, root);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Contract drift: ${fileURLToPath(path)}`);
  } else {
    await writeFile(path, content);
  }
}
